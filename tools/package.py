"""Build a deterministic source ZIP from an explicit publication allowlist."""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import re
import zipfile
import zlib
from pathlib import Path, PurePosixPath


def scan_bytes(payload):
    patterns = {
        "private filesystem path": rb"/(?:share/" + rb"project|root|Users|home)/",
        "private network address": rb"\b(?:10(?:\.\d{1,3}){3}|192\.168(?:\.\d{1,3}){2}|172\.(?:1[6-9]|2\d|3[01])(?:\.\d{1,3}){2})\b",
        "private key": rb"-----BEGIN (?:OPENSSH |RSA |EC )?PRIVATE KEY-----",
        "credential token": rb"\b(?:sk-[A-Za-z0-9_-]{16,}|hf_[A-Za-z0-9]{20,}|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,})\b",
        "credential URL": rb"https?://[^\s/:]+:[^\s/@]+@",
        "credential assignment": rb'''(?i)(?:api[_-]?key|password|access[_-]?token)\s*[:=]\s*["'][A-Za-z0-9_./+:-]{8,}["']''',
        "internal job identity": rb"\bjob-[0-9a-f]{8,}\b",
    }
    return [name for name, pattern in patterns.items() if re.search(pattern, payload)]


def checked_payload(path):
    payload = path.read_bytes()
    chunks = [payload]
    if path.suffix == ".gz":
        chunks.append(gzip.decompress(payload))
    elif path.suffix == ".pdf":
        if not payload.startswith(b"%PDF-"):
            raise ValueError(f"invalid PDF: {path.name}")
        # Inspect compressed PDF text/metadata in addition to the raw dictionaries.
        for stream in re.findall(rb"stream\r?\n(.*?)\r?\nendstream", payload, re.S):
            try:
                chunks.append(zlib.decompress(stream))
            except zlib.error:
                pass  # Uncompressed and image streams are also valid PDF content.
    else:
        payload.decode("utf-8")
    hits = sorted(set(name for chunk in chunks for name in scan_bytes(chunk)))
    if hits:
        raise ValueError(f"publication scan failed: {path.name}: {', '.join(hits)}")
    return payload


def collect(root, names):
    root = Path(root).resolve(strict=True)
    if len(names) != len(set(names)):
        raise ValueError("duplicate publication paths")
    result = {}
    forbidden = {".git", ".env", "orig", "archive", "revisions", "outputs", "checkpoints", "__pycache__"}
    for name in names:
        rel = PurePosixPath(name)
        if (rel.is_absolute() or ".." in rel.parts or str(rel) != name
                or forbidden.intersection(rel.parts) or name.startswith(".env.")):
            raise ValueError("unsafe publication path")
        path = root / name
        if path.is_symlink() or any(p.is_symlink() for p in path.parents if p != root):
            raise ValueError("publication symlinks are forbidden")
        path.resolve(strict=True).relative_to(root)
        result[name] = checked_payload(path)
    return result


def write_archive(path, payloads, *, prefix, hash_filename="sha256.json"):
    if hash_filename in payloads:
        raise ValueError("checksum manifest must be generated by the packager")
    hashes = {name: hashlib.sha256(data).hexdigest() for name, data in sorted(payloads.items())}
    content = {**payloads, hash_filename: (json.dumps(hashes, indent=2) + "\n").encode()}
    with zipfile.ZipFile(path, "x", zipfile.ZIP_DEFLATED) as archive:
        for name, data in sorted(content.items()):
            info = zipfile.ZipInfo(prefix + name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, data)
    with zipfile.ZipFile(path) as archive:
        if archive.testzip() is not None or set(archive.namelist()) != {prefix + n for n in content}:
            raise ValueError("source archive integrity failure")
        for name, expected in hashes.items():
            if hashlib.sha256(archive.read(prefix + name)).hexdigest() != expected:
                raise ValueError("source archive hash mismatch")
    return hashes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    files = json.loads((root / "publish-files.json").read_text())
    payloads = collect(root, files)
    if args.output:
        write_archive(args.output, payloads, prefix="instructreplay/")
    print(json.dumps({"scan": "PASS", "files": len(payloads), "archive": bool(args.output)}))


if __name__ == "__main__":
    main()
